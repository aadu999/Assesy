#!/bin/bash

# Cloudflare Tunnel Startup Script
# This script starts cloudflared tunnels before docker-compose based on the .env.tunnel configuration

set -e

# Load configuration
if [ -f .env.tunnel ]; then
    source .env.tunnel
else
    echo "⚠️  .env.tunnel not found. Creating default configuration..."
    cat > .env.tunnel << 'EOF'
# Cloudflare Tunnel Configuration
# Set to "true" to enable cloudflared tunnels before starting docker-compose
ENABLE_CLOUDFLARE_TUNNEL=false

# If ENABLE_CLOUDFLARE_TUNNEL=true, these tunnels will be started automatically
# Leave empty to let cloudflared generate random URLs  
FRONTEND_TUNNEL_URL=
BACKEND_TUNNEL_URL=
EOF
    source .env.tunnel
fi

# Function to start a cloudflared tunnel
start_tunnel() {
    local port=$1
    local name=$2
    local log_file="tunnel-${name}.log"
    
    echo "🌐 Starting Cloudflare Tunnel for ${name} (port ${port})..."
    
    # Start cloudflared in background and capture URL
    cloudflared tunnel --url http://localhost:${port} > "${log_file}" 2>&1 &
    local pid=$!
    echo $pid > "tunnel-${name}.pid"
    
    # Wait for tunnel to be ready and extract URL
    echo "⏳ Waiting for tunnel to establish..."
    for i in {1..30}; do
        if grep -q "https://.*trycloudflare.com" "${log_file}" 2>/dev/null; then
            local url=$(grep -o "https://[^ ]*trycloudflare.com" "${log_file}" | head -1)
            echo "✅ ${name} tunnel ready: ${url}"
            echo "${url}" > "tunnel-${name}.url"
            return 0
        fi
        sleep 1
    done
    
    echo "❌ Tunnel failed to start for ${name}"
    return 1
}

# Function to stop all tunnels
stop_tunnels() {
    echo "🛑 Stopping all cloudflare tunnels..."
    
    for pid_file in tunnel-*.pid; do
        if [ -f "${pid_file}" ]; then
            pid=$(cat "${pid_file}")
            if kill -0 $pid 2>/dev/null; then
                kill $pid
                echo "  Stopped tunnel (PID: ${pid})"
            fi
            rm "${pid_file}"
        fi
    done
    
    rm -f tunnel-*.url tunnel-*.log
    echo "✅ All tunnels stopped"
}

# Main logic
if [ "${ENABLE_CLOUDFLARE_TUNNEL}" = "true" ]; then
    echo "🚀 Cloudflare Tunnel Mode: ENABLED"
    echo "================================================"
    
    # Check if cloudflared is installed
    if ! command -v cloudflared &> /dev/null; then
        echo "❌ cloudflared is not installed!"
        echo "Please install from: https://github.com/cloudflare/cloudflared"
        echo ""
        echo "Quick install:"
        echo "  wget https://github.com/cloudflare/cloudflared/releases/latest/download/cloudflared-linux-amd64.deb"
        echo "  sudo dpkg -i cloudflared-linux-amd64.deb"
        exit 1
    fi
    
    # Clean up any existing tunnels
    stop_tunnels
    
    # Start tunnels for frontend and backend
    start_tunnel 5173 "frontend" &
    start_tunnel 3000 "backend" &
    
    wait
    
    echo ""
    echo "================================================"
    echo "📋 TUNNEL URLS:"
    echo "================================================"
    if [ -f "tunnel-frontend.url" ]; then
        FRONTEND_URL=$(cat tunnel-frontend.url)
        echo "Frontend: ${FRONTEND_URL}"
    fi
    if [ -f "tunnel-backend.url" ]; then
        BACKEND_URL=$(cat tunnel-backend.url)
        echo "Backend:  ${BACKEND_URL}"
        
        # Generate frontend config.js with backend URL
        echo "🔧 Generating frontend configuration..."
        cat > frontend/public/config.js << EOF
// Runtime configuration - Auto-generated by start.sh
// This file is regenerated every time tunnels are started
window.BACKEND_URL = '${BACKEND_URL}';
EOF
        echo "  ✅ Frontend configured to use backend: ${BACKEND_URL}"
    fi
    echo "================================================"
    echo ""
    echo "💡 Tunnel URLs will be automatically configured!"
    echo ""
    
else
    echo "🔒 Cloudflare Tunnel Mode: DISABLED"
    echo "Using local URLs (localhost)"
    echo "To enable tunnels, edit .env.tunnel and set ENABLE_CLOUDFLARE_TUNNEL=true"
fi

# Now start docker-compose
echo ""
echo "🐳 Starting Docker Compose..."
docker compose up -d

# Wait for services to be ready
echo "⏳ Waiting for services to start..."
sleep 5

# If tunnels are enabled, update the database with tunnel URLs
if [ "${ENABLE_CLOUDFLARE_TUNNEL}" = "true" ]; then
    echo ""
    echo "🔧 Configuring tunnel URLs in database..."
    
    if [ -f "tunnel-frontend.url" ]; then
        FRONTEND_URL=$(cat tunnel-frontend.url)
        
        # Update database using docker exec
        docker compose exec -T database psql -U user -d interviewdb -c \
            "INSERT INTO admin_settings (key, value) VALUES ('public_url_candidate', '${FRONTEND_URL}') 
             ON CONFLICT (key) DO UPDATE SET value = '${FRONTEND_URL}';" 2>/dev/null || echo "  ⚠️  Database update failed (services may still be starting)"
        
        echo "  ✅ Frontend URL configured: ${FRONTEND_URL}"
    fi
    
    if [ -f "tunnel-backend.url" ]; then
        BACKEND_URL=$(cat tunnel-backend.url)
        
        docker compose exec -T database psql -U user -d interviewdb -c \
            "INSERT INTO admin_settings (key, value) VALUES ('public_url_backend', '${BACKEND_URL}') 
             ON CONFLICT (key) DO UPDATE SET value = '${BACKEND_URL}';" 2>/dev/null || echo "  ⚠️  Database update failed (services may still be starting)"
        
        echo "  ✅ Backend URL configured: ${BACKEND_URL}"
    fi
    
    echo ""
    echo "✅ Tunnel URLs have been automatically configured!"
    echo "You can now share assessment links - they will use the tunnel URLs."
fi

echo ""
echo "✅ Application started successfully!"

# Show status
docker compose ps
